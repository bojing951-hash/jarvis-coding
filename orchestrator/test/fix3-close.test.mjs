const headOf = (repo) => execFileSync('git', ['-C', repo, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();

function approvedTask(label, overrides = {}) {
  const { p, head } = projectWithRepo(label);
  const vp = seedVerifyProfile(p);
  const t = seedTask({ project: p, head, verifyProfileId: vp, ...overrides });
  const challenge = svc.createAuthChallenge(t.id);
  const issued = svc.issueApproval({ task: t.id, proof: signChallenge(challenge) });
  assert.equal(issued.ok, true, issued.error);
  return { p, t, repo: join(p.dir, 'repo') };
}

