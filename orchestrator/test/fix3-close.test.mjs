const gitRepo = (dir) => {
  mkdirSync(dir, { recursive: true });
  const g = (...a) => execFileSync('git', ['-C', dir, ...a], { encoding: 'utf8' });
  g('init', '-q');
  writeFileSync(join(dir, 'a.txt'), 'x\n');
  g('add', '-A');
  g('-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'init');
  return g('rev-parse', 'HEAD').trim();
};

const fakeIsolation = {
  isolationStatus: async () => ({ available: true, backend: 'fake', image: 'fake-image', network: 'fake-net', networkInternal: true }),
  egressProxyUrl: async () => 'http://127.0.0.1:9',
  runClaudeIsolated: async ({ workdir }) => {
    writeFileSync(join(workdir, 'feature.txt'), 'generated by fake executor\n');
    return { ok: true, exitCode: 0, text: 'done', isolated: true, network: 'fake-net', image: 'fake-image', raw: '' };
  },
  runInWorkdir: async () => ({ ok: true, exitCode: 0, output: 'verify ok' }),
  killContainer: async (name) => ({ ok: true, confirmed: true, name })
};

function projectWithRepo(label) {
  const p = svc.createProject({ name: label, slug: `${label}-${Date.now().toString(36)}` });
  const head = gitRepo(join(p.dir, 'repo'));
  return { p, head };
}

function seedVerifyProfile(project, { program = process.execPath, argv = [] } = {}) {
  const id = `vpr_${Math.random().toString(36).slice(2, 10)}`;
  svc.db()
    .prepare('INSERT INTO verify_profiles (id,project_id,name,program,argv,cwd,timeout_ms,created_by,created_at) VALUES (?,?,?,?,?,?,?,?,?)')
    .run(id, project.id, `verify-${id}`, program, JSON.stringify(argv), null, 300_000, 'test', new Date().toISOString());
  return id;
}

function seedTask({ project, head, verifyProfileId, mode = 'acceptEdits', commit = true, commitPaths = ['feature.txt'] }) {
  return svc.createTask({
    project: project.id,
    title: '合法写入任务',
    input: 'write feature.txt',
    kind: 'executor',
    executor: 'claude-code',
    executorConfig: {
      mode,
      repo: 'repo',
      base_commit: head,
      commit,
      commit_paths: commitPaths,
      verify_profile_id: verifyProfileId
    }
  });
}

function signChallenge(challenge) {
  const signer = createSign('sha256');
  signer.update(challenge.payload);
  return {
    nonce: challenge.nonce,
    payload: challenge.payload,
    signatureB64: signer.sign(privateKey).toString('base64')
  };
}

/* ------------------------------- PRE-A01 --------------------------------- */

test('PRE-A01 同一 Execution 消耗审批后仍可完成合法提交', async () => {
  const { p, head } = projectWithRepo('a01');
  const vp = seedVerifyProfile(p);
  const t = seedTask({ project: p, head, verifyProfileId: vp });
  const challenge = svc.createAuthChallenge(t.id);
  const proof = signChallenge(challenge);
  const issued = svc.issueApproval({ task: t.id, proof });
  assert.equal(issued.ok, true, JSON.stringify(issued));

  const r = await svc.runTask(t.id, { isolation: fakeIsolation });
  assert.equal(
    r.ok,
    true,
    JSON.stringify({ blocked: r.blocked, commit: r.commit, verdict: r.verdict, task: svc.getTask(t.id).status })
  );
  const done = svc.getTask(t.id);
  assert.equal(done.status, 'done');
  assert.ok(r.commit?.sha, '必须记录真实 commit SHA');
  assert.equal(r.commit.refVerified, true, '必须能从 ref 取回同一 SHA');
  assert.equal(r.task.status, 'done');

  const approval = svc.db().prepare('SELECT * FROM approvals WHERE task_id=?').get(t.id);
  assert.ok(approval.used_at, '审批必须已消耗');
  assert.equal(approval.execution_id, r.execution, '审批必须记录取得它的 Execution');
  assert.equal(svc.findValidApproval(t.id, approval.digest).valid, false, '已消耗审批不得再给新执行使用');
  const tokenFile = join(process.env.JARVIS_HOME, 'proxy', 'active-tokens.json');
  assert.deepEqual(JSON.parse(readFileSync(tokenFile, 'utf8')), {}, '执行结束后模型令牌必须撤销');
});

