test('PRE-A01 已消耗审批不得被新执行复用', async () => {
  const { t, repo } = approvedTask('a01-reuse');
  const before = headOf(repo);
  const first = await svc.runTask(t.id, { isolation: fakeIsolation });
  assert.equal(first.ok, true, JSON.stringify(first));
  const approval = svc.db().prepare('SELECT * FROM approvals WHERE task_id=?').get(t.id);
  assert.equal(svc.findValidApproval(t.id, approval.digest).valid, false);

  // 模拟重试入口：任务回到 retry_pending，但旧审批仍归第一次执行所有
  svc.updateTask(t.id, { status: 'retry_pending' });
  const again = await svc.runTask(t.id, { isolation: fakeIsolation });
  assert.equal(again.ok, false);
  assert.equal(again.blocked, 'needs_approval');
  const runningAfter = svc.db().prepare("SELECT COUNT(*) AS n FROM executions WHERE task_id=? AND status='running'").get(t.id).n;
  assert.equal(runningAfter, 0, '旧审批不得启动新的执行');
  assert.equal(headOf(repo), before, '重试不得改变仓库 HEAD');
  const refSha = execFileSync('git', ['-C', repo, 'rev-parse', `refs/heads/jarvis/${t.id}`], { encoding: 'utf8' }).trim();
  assert.equal(refSha, first.commit.sha, '第一次执行的 Ref 仍应指向真实 Commit');
});

/* -------------------------- 取消 / 提交竞态 ---------------------------- */

test('取消在提交前成立：不得开始 Git Commit', async () => {
  const { t, repo } = approvedTask('cancel-before');
  const before = headOf(repo);
  let releaseRun;
  let markStarted;
  const started = new Promise((r) => { markStarted = r; });
  const hold = new Promise((r) => { releaseRun = r; });
  const gatedIso = {
    ...fakeIsolation,
    runClaudeIsolated: async ({ workdir }) => {
      writeFileSync(join(workdir, 'feature.txt'), 'x\n');
      markStarted();
      await hold;
      return { ok: true, exitCode: 0, text: 'done', isolated: true, network: 'fake-net', image: 'fake-image', raw: '' };
    }
  };
  let commitCalled = false;
  const spyExecutor = {
    ...ex,
    gitCommit: async (args) => { commitCalled = true; return ex.gitCommit(args); }
  };
  const running = svc.runTask(t.id, { isolation: gatedIso, executor: spyExecutor });
  await started;
  const cancelled = await svc.cancelTask(t.id, { isolation: gatedIso });
  assert.equal(cancelled.ok, true, JSON.stringify(cancelled));
  releaseRun();
  const r = await running;
  assert.equal(r.ok, false);
  assert.equal(r.blocked, 'cancelled');
  assert.equal(commitCalled, false, '取消成立后不得调用 gitCommit');
  assert.equal(headOf(repo), before, '取消后仓库 HEAD 不得变化');
  assert.equal(svc.getTask(t.id).status, 'cancelled');
  const tokenFile = join(process.env.JARVIS_HOME, 'proxy', 'active-tokens.json');
  assert.deepEqual(JSON.parse(readFileSync(tokenFile, 'utf8')), {}, '取消后模型令牌必须撤销');
});

test('提交中取消：不得立即虚报 cancelled，提交完成后必须记录真实 Commit/Ref', async () => {
  const { t } = approvedTask('cancel-during');
  let releaseCommit;
  let markCommitStarted;
  const commitStarted = new Promise((r) => { markCommitStarted = r; });
  const commitHold = new Promise((r) => { releaseCommit = r; });
  const spyExecutor = {
    ...ex,
    gitCommit: async (args) => {
      markCommitStarted();
      await commitHold;
      return ex.gitCommit(args);
    }
  };
  const running = svc.runTask(t.id, { isolation: fakeIsolation, executor: spyExecutor });
  await commitStarted;
  assert.equal(svc.getTask(t.id).status, 'committing');

  const cancelled = await svc.cancelTask(t.id, { isolation: fakeIsolation });
  assert.equal(cancelled.ok, false);
  assert.equal(cancelled.blocked, 'commit_in_progress');
  assert.equal(svc.getTask(t.id).status, 'committing', '提交中取消不得改写为 cancelled');

  releaseCommit();
  const r = await running;
  assert.equal(r.ok, true, JSON.stringify({ verdict: r.verdict, commit: r.commit }));
  assert.ok(r.commit?.sha);
  assert.equal(r.commit.refVerified, true);
  assert.equal(svc.getTask(t.id).status, 'done');
  const after = await svc.cancelTask(t.id, { isolation: fakeIsolation });
  assert.equal(after.ok, false, '提交完成后不能再虚报取消');
  assert.equal(svc.getTask(t.id).status, 'done');
});

