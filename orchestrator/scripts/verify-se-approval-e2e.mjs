#!/usr/bin/env node
/**
 * 真实 macOS Secure Enclave 审批 + 合法 Git 写入 E2E。
 *
 * 需要：
 *   - 已构建的 jarvis-auth（默认 /tmp/jarvis-auth-build/jarvis-auth）
 *   - 已生成的 approval.sekey + pubkey.der（默认 /tmp/jarvis-auth-e2e/home）
 *   - 用户本人完成 Touch ID / 系统密码
 *
 * 说明：Docker/Claude Code 容器在本脚本中用受控替身完成文件修改，
 * Git commit / ref 验证 / Task 状态是真实的。真实容器的隔离由
 * docker-fault / FIX3-D 测试和本机 Docker 证据单独覆盖。
 *
 * 用法：
 *   JARVIS_E2E_HOME=/tmp/jarvis-auth-e2e/home \
 *   JARVIS_AUTH_SIGNER=/tmp/jarvis-auth-build/jarvis-auth \
 *   node orchestrator/scripts/verify-se-approval-e2e.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const HOME_DIR = process.env.JARVIS_E2E_HOME || '/tmp/jarvis-auth-e2e/home';
const SIGNER = process.env.JARVIS_AUTH_SIGNER || '/tmp/jarvis-auth-build/jarvis-auth';
process.env.HOME = HOME_DIR;
process.env.JARVIS_HOME = join(HOME_DIR, 'jarvis');
process.env.JARVIS_DB = join(process.env.JARVIS_HOME, 'state.db');
process.env.JARVIS_AUTH_SIGNER = SIGNER;

const svc = await import('../src/service.mjs');
const sec = await import('../src/security.mjs');

const repo = join(HOME_DIR, 'e2e-repo');
mkdirSync(repo, { recursive: true });
mkdirSync(join(HOME_DIR, '.claude'), { recursive: true });
writeFileSync(join(HOME_DIR, '.claude/settings.json'), JSON.stringify({ env: { ANTHROPIC_MODEL: 'test-model' } }));
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' });
try { git('init', '-q'); } catch {}
writeFileSync(join(repo, 'a.txt'), 'base\n');
git('add', '-A');
git('-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'init');
const head = git('rev-parse', 'HEAD').trim();

const project = svc.createProject({ name: 'SE legal E2E', slug: `se-legal-${Date.now().toString(36)}` });
const workRepo = join(project.dir, 'repo');
mkdirSync(workRepo, { recursive: true });
const wg = (...args) => execFileSync('git', ['-C', workRepo, ...args], { encoding: 'utf8' });
try { wg('init', '-q'); } catch {}
writeFileSync(join(workRepo, 'a.txt'), 'base\n');
wg('add', '-A');
wg('-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'init');
const base = wg('rev-parse', 'HEAD').trim();

// 校验配置属于可信登记数据；本脚本直接落库作为测试准备，登记边界由
// createVerifyProfile 的签名测试单独覆盖。
const vpId = `vpr_e2e_${Date.now().toString(36)}`;
svc.db()
  .prepare('INSERT INTO verify_profiles (id,project_id,name,program,argv,cwd,timeout_ms,created_by,created_at) VALUES (?,?,?,?,?,?,?,?,?)')
  .run(vpId, project.id, 'node-ok', process.execPath, '[]', null, 300_000, 'e2e', new Date().toISOString());

const task = svc.createTask({
  project: project.id,
  title: 'SE 真实审批 + 合法提交',
  input: '写入 feature.txt 并提交',
  kind: 'executor',
  executor: 'claude-code',
  executorConfig: {
    mode: 'acceptEdits',
    repo: 'repo',
    base_commit: base,
    commit: true,
    commit_paths: ['feature.txt'],
    verify_profile_id: vpId
  }
});

const challenge = svc.createAuthChallenge(task.id);
const payloadPath = join(process.env.JARVIS_HOME, 'run', 'se-legal-payload.json');
mkdirSync(join(process.env.JARVIS_HOME, 'run'), { recursive: true });
writeFileSync(payloadPath, challenge.payload, { mode: 0o600 });

const signatureB64 = execFileSync(
  SIGNER,
  ['sign', payloadPath, challenge.reason.slice(0, 500)],
  { encoding: 'utf8', timeout: 180_000 }
).trim();
const verified = sec.verifyApprovalSignature({ payload: challenge.payload, signatureB64 });
if (!verified.ok) {
  console.error(`signature verification failed: ${verified.error}`);
  process.exit(1);
}
const issued = svc.issueApproval({
  task: task.id,
  proof: { nonce: challenge.nonce, payload: challenge.payload, signatureB64 }
});
if (!issued.ok) {
  console.error(`approval issuance failed: ${issued.error}`);
  process.exit(1);
}

const fakeIsolation = {
  isolationStatus: async () => ({ available: true, backend: 'fake-e2e', image: 'fake-e2e', network: 'fake-e2e', networkInternal: true }),
  egressProxyUrl: async () => 'http://127.0.0.1:9',
  runClaudeIsolated: async ({ workdir }) => {
    writeFileSync(join(workdir, 'feature.txt'), 'generated by controlled executor\n');
    return { ok: true, exitCode: 0, text: 'controlled executor ok', isolated: true, network: 'fake-e2e', image: 'fake-e2e', raw: '' };
  },
  runInWorkdir: async () => ({ ok: true, exitCode: 0, output: 'verify ok' })
};

const result = await svc.runTask(task.id, { isolation: fakeIsolation });
const latest = svc.getTask(task.id);
const approval = svc.db().prepare('SELECT * FROM approvals WHERE task_id=?').get(task.id);
const execution = svc.db().prepare('SELECT * FROM executions WHERE id=?').get(result.execution);
const refSha = execFileSync('git', ['-C', workRepo, 'rev-parse', `refs/heads/jarvis/${task.id}`], { encoding: 'utf8' }).trim();

const evidence = {
  task: task.id,
  approvalId: approval?.id,
  approvalExecutionId: approval?.execution_id,
  executionId: result.execution,
  executionStatus: execution?.status,
  taskStatus: latest.status,
  commitSha: result.commit?.sha ?? null,
  ref: result.commit?.ref ?? null,
  refVerified: result.commit?.refVerified ?? false,
  refMatchesCommit: refSha === result.commit?.sha,
  verdict: result.verdict?.status ?? null,
  reasons: result.verdict?.reasons ?? [],
  tokenFileEmpty: ['proxy/active-tokens.json'].every((p) => {
    try {
      const raw = execFileSync('cat', [join(process.env.JARVIS_HOME, p)], { encoding: 'utf8' });
      return raw.trim() === '{}';
    } catch {
      return true;
    }
  })
};
console.log(JSON.stringify(evidence, null, 2));

if (
  latest.status !== 'done' ||
  result.verdict?.status !== 'done' ||
  !result.commit?.sha ||
  !result.commit?.refVerified ||
  refSha !== result.commit.sha ||
  approval?.execution_id !== result.execution ||
  execution?.status !== 'ok'
) {
  process.exit(1);
}
